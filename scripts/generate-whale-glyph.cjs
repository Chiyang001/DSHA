// Preserve the installed official Harness logo and swim morphs in the native overlay.
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const primitives = fs.readFileSync(path.join(root, 'runtime/node_modules/@deepseek-ai/dsh-client-ui-primitives/lib/index.js'), 'utf8')
const conversation = fs.readFileSync(path.join(root, 'runtime/node_modules/@deepseek-ai/dsh-client-ui-conversation/lib/client.js'), 'utf8')
function extract(source, name) {
  const match = source.match(new RegExp(`const ${name} = "([^"]+)";`))
  if (!match) throw new Error(`Missing official geometry: ${name}`)
  const commands = [...match[1].matchAll(/([MCLZ])([^MCLZ]*)/g)].map(([,op,args]) => ({op,values:(args.match(/-?\d+(?:\.\d+)?(?:e[-+]?\d+)?/gi)||[]).map(Number)}))
  if (commands.map(c=>c.op+c.values.length).join() !== commands.map(c=>c.op+({M:2,C:6,L:2,Z:0}[c.op])).join()) throw new Error('Unexpected SVG commands')
  return commands
}
const shapes = [extract(primitives,'FISH_LOGO_PATH'),extract(conversation,'HERO_SWIM_UP_PATH'),extract(conversation,'HERO_SWIM_DOWN_PATH')]
if (shapes.some(s=>s.map(c=>c.op).join()!==shapes[0].map(c=>c.op).join())) throw new Error('Official morph topology changed')
const arrays = shapes.map((s,i)=>`    private static final float[] ${['REST','UP','DOWN'][i]} = {${s.flatMap(c=>c.values).map(v=>v+'f').join(',')}};`).join('\n')
const java = `package app.dsh.android;

import android.animation.ValueAnimator;
import android.content.Context;
import android.graphics.*;
import android.view.View;
import android.view.animation.LinearInterpolator;
import android.view.animation.PathInterpolator;

/** Geometry and 1.6 s morph keyframes from installed official Harness HeroFish.
 * Generated by scripts/generate-whale-glyph.cjs. No WebView or raster frames. */
final class WhaleTaskGlyph extends View {
${arrays}
    private static final String COMMANDS = "${shapes[0].map(c=>c.op).join('')}";
    private final Paint paint = new Paint(Paint.ANTI_ALIAS_FLAG);
    private final Path shape = new Path();
    private final PathInterpolator easing = new PathInterpolator(.45f,0,.55f,1);
    private final float[] points = new float[REST.length];
    private ValueAnimator animator;
    private boolean running;
    private float phase;
    WhaleTaskGlyph(Context context){super(context);setImportantForAccessibility(IMPORTANT_FOR_ACCESSIBILITY_NO);}
    void setRunning(boolean value){
        if(running==value)return;
        running=value;stopAnimation();
        if(value && isAttachedToWindow() && ValueAnimator.areAnimatorsEnabled()){
            animator=ValueAnimator.ofFloat(0,1);animator.setDuration(1600);
            animator.setInterpolator(new LinearInterpolator());animator.setRepeatCount(ValueAnimator.INFINITE);
            animator.addUpdateListener(a->{phase=(float)a.getAnimatedValue();invalidate();});animator.start();
        }
        invalidate();
    }
    private void stopAnimation(){if(animator!=null){animator.cancel();animator=null;}phase=0;}
    @Override protected void onAttachedToWindow(){super.onAttachedToWindow();if(running){running=false;setRunning(true);}}
    @Override protected void onDetachedFromWindow(){stopAnimation();super.onDetachedFromWindow();}
    @Override protected void onDraw(Canvas canvas){
        float[] from=REST,to=REST;float fraction=0;
        if(running && animator!=null){
            if(phase<.35f){to=UP;fraction=phase/.35f;}
            else if(phase<.55f){from=UP;fraction=(phase-.35f)/.20f;}
            else if(phase<.75f){to=DOWN;fraction=(phase-.55f)/.20f;}
            else {from=DOWN;fraction=(phase-.75f)/.25f;}
        }
        float blend=easing.getInterpolation(fraction);
        for(int i=0;i<points.length;i++)points[i]=from[i]+(to[i]-from[i])*blend;
        shape.reset();int offset=0;
        for(int i=0;i<COMMANDS.length();i++){
            switch(COMMANDS.charAt(i)){
                case 'M':shape.moveTo(points[offset],points[offset+1]);offset+=2;break;
                case 'L':shape.lineTo(points[offset],points[offset+1]);offset+=2;break;
                case 'C':shape.cubicTo(points[offset],points[offset+1],points[offset+2],points[offset+3],points[offset+4],points[offset+5]);offset+=6;break;
                case 'Z':shape.close();break;
            }
        }
        float density=getResources().getDisplayMetrics().density;
        float scale=Math.min((getWidth()-2*density)/23.8f,(getHeight()-4*density)/17.1f);
        canvas.save();canvas.translate((getWidth()-23.8f*scale)/2,(getHeight()-17.1f*scale)/2);
        canvas.scale(scale,scale);
        if(animator!=null)canvas.rotate((float)(-2.4*Math.sin(phase*2*Math.PI)),11.58f,10.22f);
        paint.setColor(running?Color.rgb(142,198,255):Color.rgb(134,152,179));canvas.drawPath(shape,paint);canvas.restore();
    }
}
`
fs.writeFileSync(path.join(root,'app/src/main/java/app/dsh/android/WhaleTaskGlyph.java'),java)
console.log('Official whale geometry generated:', shapes[0].length, 'commands;', shapes[0].flatMap(c=>c.values).length, 'coordinates per pose')
